uint8_t DHT11_Read(uint8_t *humidity, uint8_t *temperature) {
    uint8_t data[5] = {0};
    uint32_t timeout = 0;

    /* 1. Host Start Signal */
    Set_Pin_Output();
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_8, GPIO_PIN_RESET);
    HAL_Delay(18); // Hold LOW for 18ms
    
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_8, GPIO_PIN_SET);
    delay_us(30);  // Hold HIGH for 30us
    
    Set_Pin_Input(); // Release line for DHT11 response

    /* 2. Wait for DHT11 Handshake (LOW -> HIGH -> LOW) */
    timeout = 0;
    while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_SET) {
        if (++timeout > 100) return 0;
        delay_us(1);
    }

    timeout = 0;
    while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_RESET) {
        if (++timeout > 100) return 0;
        delay_us(1);
    }

    timeout = 0;
    while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_SET) {
        if (++timeout > 100) return 0;
        delay_us(1);
    }

    /* 3. Read 40 Bits */
    for (int j = 0; j < 5; j++) {
        for (int i = 0; i < 8; i++) {
            while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_RESET);

            delay_us(40); // Sample in middle of high pulse

            if (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_SET) {
                data[j] |= (1 << (7 - i));
                while (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_8) == GPIO_PIN_SET);
            }
        }
    }

    /* 4. Checksum Verification */
    if (data[4] == ((data[0] + data[1] + data[2] + data[3]) & 0xFF)) {
        *humidity = data[0];
        *temperature = data[2];
        return 1;
    }

    return 0;
}

